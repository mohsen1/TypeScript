/**
 * Node Modules Resolution - Specialized resolver for node_modules.
 *
 * This module provides enhanced support for resolving modules from
 * node_modules directories, including support for package exports,
 * subpath imports, and @types packages.
 */

namespace ts {
    /**
     * Options for node_modules resolution.
     */
    export interface NodeModulesResolverOptions {
        /** Compiler options */
        compilerOptions: CompilerOptions;
        /** File system host */
        host: ModuleResolutionHost;
        /** Whether to resolve @types packages */
        resolveTypes?: boolean;
        /** Custom node_modules paths */
        nodeModulesPaths?: readonly string[];
    }

    /**
     * Result of resolving from node_modules.
     */
    export interface NodeModulesResolutionResult {
        /** The resolved file path */
        resolvedPath: string | undefined;
        /** The package.json info */
        packageInfo: PackageInfo | undefined;
        /** Whether this is from @types */
        isTypesPackage: boolean;
        /** Failed lookup locations */
        failedLookups: string[];
    }

    /**
     * Information about a resolved package.
     */
    export interface PackageInfo {
        /** Package name */
        name: string;
        /** Package version */
        version: string;
        /** Path to the package directory */
        packageDirectory: string;
        /** Path to package.json */
        packageJsonPath: string;
        /** The package.json contents */
        packageJson: ParsedPackageJson;
    }

    /**
     * Parsed package.json with typed fields.
     */
    export interface ParsedPackageJson {
        name?: string;
        version?: string;
        main?: string;
        module?: string;
        types?: string;
        typings?: string;
        exports?: PackageExports;
        imports?: PackageImports;
        typesVersions?: TypesVersions;
        dependencies?: Record<string, string>;
        devDependencies?: Record<string, string>;
        peerDependencies?: Record<string, string>;
    }

    /**
     * Package exports field structure.
     */
    export type PackageExports =
        | string
        | string[]
        | { [key: string]: PackageExports }
        | null;

    /**
     * Package imports field structure (subpath imports).
     */
    export type PackageImports = Record<string, PackageExports>;

    /**
     * TypesVersions field for version-specific type definitions.
     */
    export type TypesVersions = Record<string, Record<string, string[]>>;

    /**
     * Specialized resolver for node_modules.
     */
    export class NodeModulesResolver {
        private readonly options: CompilerOptions;
        private readonly host: ModuleResolutionHost;
        private readonly resolveTypes: boolean;
        private readonly customPaths: readonly string[];

        /** Cache for package.json files */
        private readonly packageJsonCache: Map<string, ParsedPackageJson | null> = new Map();

        /** Cache for resolved packages */
        private readonly packageCache: Map<string, PackageInfo | undefined> = new Map();

        constructor(resolverOptions: NodeModulesResolverOptions) {
            this.options = resolverOptions.compilerOptions;
            this.host = resolverOptions.host;
            this.resolveTypes = resolverOptions.resolveTypes ?? true;
            this.customPaths = resolverOptions.nodeModulesPaths ?? [];
        }

        /**
         * Resolve a module from node_modules.
         */
        public resolve(
            moduleName: string,
            containingDirectory: string,
            subpath?: string
        ): NodeModulesResolutionResult {
            const failedLookups: string[] = [];

            // Parse the module name
            const { packageName, subpathPart } = parsePackageName(moduleName);
            const effectiveSubpath = subpath ?? subpathPart;

            // Look for the package
            const packageInfo = this.findPackage(packageName, containingDirectory, failedLookups);

            if (!packageInfo) {
                // Try @types package
                if (this.resolveTypes && !packageName.startsWith("@types/")) {
                    const typesPackageName = `@types/${packageName.replace("/", "__")}`;
                    const typesResult = this.resolve(typesPackageName, containingDirectory, effectiveSubpath);
                    if (typesResult.resolvedPath) {
                        return { ...typesResult, isTypesPackage: true };
                    }
                    failedLookups.push(...typesResult.failedLookups);
                }

                return {
                    resolvedPath: undefined,
                    packageInfo: undefined,
                    isTypesPackage: false,
                    failedLookups,
                };
            }

            // Resolve within the package
            const resolvedPath = this.resolveWithinPackage(packageInfo, effectiveSubpath, failedLookups);

            return {
                resolvedPath,
                packageInfo,
                isTypesPackage: packageName.startsWith("@types/"),
                failedLookups,
            };
        }

        /**
         * Find a package in node_modules.
         */
        private findPackage(
            packageName: string,
            containingDirectory: string,
            failedLookups: string[]
        ): PackageInfo | undefined {
            // Check cache
            const cacheKey = `${containingDirectory}|${packageName}`;
            const cached = this.packageCache.get(cacheKey);
            if (cached !== undefined) {
                return cached;
            }

            // Search node_modules directories
            const searchPaths = [
                ...this.customPaths,
                ...this.getNodeModulesSearchPaths(containingDirectory),
            ];

            for (const searchPath of searchPaths) {
                const packageDir = combinePaths(searchPath, packageName);
                const packageJsonPath = combinePaths(packageDir, "package.json");

                if (this.host.fileExists(packageJsonPath)) {
                    const packageJson = this.readPackageJson(packageJsonPath);
                    if (packageJson) {
                        const info: PackageInfo = {
                            name: packageJson.name ?? packageName,
                            version: packageJson.version ?? "0.0.0",
                            packageDirectory: packageDir,
                            packageJsonPath,
                            packageJson,
                        };
                        this.packageCache.set(cacheKey, info);
                        return info;
                    }
                }

                failedLookups.push(packageJsonPath);
            }

            this.packageCache.set(cacheKey, undefined);
            return undefined;
        }

        /**
         * Get node_modules search paths by walking up the directory tree.
         */
        private getNodeModulesSearchPaths(startDirectory: string): string[] {
            const paths: string[] = [];
            let directory = startDirectory;

            while (true) {
                const nodeModulesPath = combinePaths(directory, "node_modules");
                paths.push(nodeModulesPath);

                const parent = getDirectoryPath(directory);
                if (parent === directory) {
                    break;
                }
                directory = parent;
            }

            return paths;
        }

        /**
         * Resolve a subpath within a package.
         */
        private resolveWithinPackage(
            packageInfo: PackageInfo,
            subpath: string | undefined,
            failedLookups: string[]
        ): string | undefined {
            const { packageJson, packageDirectory } = packageInfo;

            // Handle exports field
            if (packageJson.exports !== undefined) {
                const exportPath = subpath ? `./${subpath}` : ".";
                const resolved = this.resolvePackageExports(
                    packageDirectory,
                    packageJson.exports,
                    exportPath,
                    failedLookups
                );
                if (resolved) {
                    return resolved;
                }
            }

            // Handle typesVersions
            if (packageJson.typesVersions) {
                const resolved = this.resolveTypesVersions(
                    packageDirectory,
                    packageJson.typesVersions,
                    subpath,
                    failedLookups
                );
                if (resolved) {
                    return resolved;
                }
            }

            // No subpath - resolve package root
            if (!subpath) {
                // Try types/typings field
                const typesField = packageJson.types ?? packageJson.typings;
                if (typesField) {
                    const typesPath = combinePaths(packageDirectory, typesField);
                    if (this.host.fileExists(typesPath)) {
                        return typesPath;
                    }
                    failedLookups.push(typesPath);
                }

                // Try main field
                if (packageJson.main) {
                    const mainPath = combinePaths(packageDirectory, packageJson.main);
                    const resolved = this.tryResolveFile(mainPath, failedLookups);
                    if (resolved) {
                        return resolved;
                    }
                }

                // Try index files
                return this.tryResolveFile(combinePaths(packageDirectory, "index"), failedLookups);
            }

            // Resolve subpath directly
            const fullPath = combinePaths(packageDirectory, subpath);
            return this.tryResolveFile(fullPath, failedLookups);
        }

        /**
         * Resolve package exports field.
         */
        private resolvePackageExports(
            packageDirectory: string,
            exports: PackageExports,
            exportPath: string,
            failedLookups: string[]
        ): string | undefined {
            if (exports === null) {
                return undefined;
            }

            if (typeof exports === "string") {
                if (exportPath === ".") {
                    const resolved = combinePaths(packageDirectory, exports);
                    return this.tryResolveFile(resolved, failedLookups);
                }
                return undefined;
            }

            if (Array.isArray(exports)) {
                for (const exp of exports) {
                    const resolved = this.resolvePackageExports(packageDirectory, exp, exportPath, failedLookups);
                    if (resolved) {
                        return resolved;
                    }
                }
                return undefined;
            }

            // Object exports
            // Check for exact match first
            if (exportPath in exports) {
                return this.resolveConditionalExports(
                    packageDirectory,
                    exports[exportPath],
                    failedLookups
                );
            }

            // Check for pattern matches
            for (const key of Object.keys(exports)) {
                if (key.includes("*")) {
                    const match = this.matchExportPattern(key, exportPath);
                    if (match !== undefined) {
                        const target = exports[key];
                        if (typeof target === "string") {
                            const resolvedTarget = target.replace("*", match);
                            const resolved = combinePaths(packageDirectory, resolvedTarget);
                            return this.tryResolveFile(resolved, failedLookups);
                        }
                    }
                }
            }

            // Check conditional exports at root
            if (exportPath === ".") {
                return this.resolveConditionalExports(packageDirectory, exports, failedLookups);
            }

            return undefined;
        }

        /**
         * Resolve conditional exports (types, import, require, default).
         */
        private resolveConditionalExports(
            packageDirectory: string,
            exports: PackageExports,
            failedLookups: string[]
        ): string | undefined {
            if (exports === null) {
                return undefined;
            }

            if (typeof exports === "string") {
                const resolved = combinePaths(packageDirectory, exports);
                return this.tryResolveFile(resolved, failedLookups);
            }

            if (Array.isArray(exports)) {
                for (const exp of exports) {
                    const resolved = this.resolveConditionalExports(packageDirectory, exp, failedLookups);
                    if (resolved) {
                        return resolved;
                    }
                }
                return undefined;
            }

            // Priority order for conditions
            const conditions = ["types", "import", "require", "default"];

            for (const condition of conditions) {
                if (condition in exports) {
                    const resolved = this.resolveConditionalExports(
                        packageDirectory,
                        exports[condition],
                        failedLookups
                    );
                    if (resolved) {
                        return resolved;
                    }
                }
            }

            return undefined;
        }

        /**
         * Resolve typesVersions field.
         */
        private resolveTypesVersions(
            packageDirectory: string,
            typesVersions: TypesVersions,
            subpath: string | undefined,
            failedLookups: string[]
        ): string | undefined {
            const tsVersion = version; // TypeScript version

            for (const versionRange of Object.keys(typesVersions)) {
                if (this.matchVersionRange(versionRange, tsVersion)) {
                    const mapping = typesVersions[versionRange];
                    const lookupPath = subpath ? `./${subpath}` : ".";

                    for (const pattern of Object.keys(mapping)) {
                        const match = this.matchExportPattern(pattern, lookupPath);
                        if (match !== undefined) {
                            const targets = mapping[pattern];
                            for (const target of targets) {
                                const resolvedTarget = target.replace("*", match);
                                const resolved = combinePaths(packageDirectory, resolvedTarget);
                                const file = this.tryResolveFile(resolved, failedLookups);
                                if (file) {
                                    return file;
                                }
                            }
                        }
                    }
                }
            }

            return undefined;
        }

        /**
         * Match an export pattern like "./*" against a path.
         */
        private matchExportPattern(pattern: string, path: string): string | undefined {
            const starIndex = pattern.indexOf("*");
            if (starIndex === -1) {
                return pattern === path ? "" : undefined;
            }

            const prefix = pattern.substring(0, starIndex);
            const suffix = pattern.substring(starIndex + 1);

            if (path.startsWith(prefix) && path.endsWith(suffix)) {
                return path.substring(prefix.length, path.length - suffix.length);
            }

            return undefined;
        }

        /**
         * Match a semver version range.
         */
        private matchVersionRange(range: string, version: string): boolean {
            // Simple matching for common patterns
            if (range === "*") {
                return true;
            }

            if (range.startsWith(">=")) {
                const minVersion = range.substring(2).trim();
                return this.compareVersions(version, minVersion) >= 0;
            }

            if (range.startsWith("<=")) {
                const maxVersion = range.substring(2).trim();
                return this.compareVersions(version, maxVersion) <= 0;
            }

            if (range.startsWith(">")) {
                const minVersion = range.substring(1).trim();
                return this.compareVersions(version, minVersion) > 0;
            }

            if (range.startsWith("<")) {
                const maxVersion = range.substring(1).trim();
                return this.compareVersions(version, maxVersion) < 0;
            }

            // Exact match
            return version === range;
        }

        /**
         * Compare two semver versions.
         */
        private compareVersions(a: string, b: string): number {
            const partsA = a.split(".").map(n => parseInt(n, 10) || 0);
            const partsB = b.split(".").map(n => parseInt(n, 10) || 0);

            for (let i = 0; i < Math.max(partsA.length, partsB.length); i++) {
                const partA = partsA[i] ?? 0;
                const partB = partsB[i] ?? 0;

                if (partA < partB) return -1;
                if (partA > partB) return 1;
            }

            return 0;
        }

        /**
         * Try to resolve a file with extension lookup.
         */
        private tryResolveFile(path: string, failedLookups: string[]): string | undefined {
            // Try exact path
            if (this.host.fileExists(path)) {
                return path;
            }
            failedLookups.push(path);

            // Try TypeScript extensions
            const tsExtensions = [Extension.Ts, Extension.Tsx, Extension.Dts];
            for (const ext of tsExtensions) {
                const candidate = path + ext;
                if (this.host.fileExists(candidate)) {
                    return candidate;
                }
                failedLookups.push(candidate);
            }

            // Try JavaScript extensions if allowJs
            if (this.options.allowJs) {
                const jsExtensions = [Extension.Js, Extension.Jsx];
                for (const ext of jsExtensions) {
                    const candidate = path + ext;
                    if (this.host.fileExists(candidate)) {
                        return candidate;
                    }
                    failedLookups.push(candidate);
                }
            }

            // Try as directory with index
            for (const ext of tsExtensions) {
                const indexPath = combinePaths(path, "index" + ext);
                if (this.host.fileExists(indexPath)) {
                    return indexPath;
                }
                failedLookups.push(indexPath);
            }

            return undefined;
        }

        /**
         * Read and cache a package.json file.
         */
        private readPackageJson(path: string): ParsedPackageJson | null {
            const cached = this.packageJsonCache.get(path);
            if (cached !== undefined) {
                return cached;
            }

            try {
                const content = this.host.readFile(path);
                if (content) {
                    const json = JSON.parse(content) as ParsedPackageJson;
                    this.packageJsonCache.set(path, json);
                    return json;
                }
            } catch {
                // Invalid JSON
            }

            this.packageJsonCache.set(path, null);
            return null;
        }

        /**
         * Clear the resolver cache.
         */
        public clearCache(): void {
            this.packageJsonCache.clear();
            this.packageCache.clear();
        }

        /**
         * Get package info for a resolved module.
         */
        public getPackageInfo(modulePath: string): PackageInfo | undefined {
            // Walk up to find package.json
            let directory = getDirectoryPath(modulePath);

            while (true) {
                const packageJsonPath = combinePaths(directory, "package.json");

                if (this.host.fileExists(packageJsonPath)) {
                    const packageJson = this.readPackageJson(packageJsonPath);
                    if (packageJson) {
                        return {
                            name: packageJson.name ?? "",
                            version: packageJson.version ?? "0.0.0",
                            packageDirectory: directory,
                            packageJsonPath,
                            packageJson,
                        };
                    }
                }

                const parent = getDirectoryPath(directory);
                if (parent === directory) {
                    break;
                }
                directory = parent;
            }

            return undefined;
        }
    }

    /**
     * Parse a package name into package name and subpath.
     */
    function parsePackageName(moduleName: string): { packageName: string; subpathPart: string | undefined } {
        // Handle scoped packages @scope/package/subpath
        if (moduleName.startsWith("@")) {
            const slashIndex = moduleName.indexOf("/", 1);
            if (slashIndex === -1) {
                return { packageName: moduleName, subpathPart: undefined };
            }

            const secondSlash = moduleName.indexOf("/", slashIndex + 1);
            if (secondSlash === -1) {
                return { packageName: moduleName, subpathPart: undefined };
            }

            return {
                packageName: moduleName.substring(0, secondSlash),
                subpathPart: moduleName.substring(secondSlash + 1),
            };
        }

        // Regular package package/subpath
        const slashIndex = moduleName.indexOf("/");
        if (slashIndex === -1) {
            return { packageName: moduleName, subpathPart: undefined };
        }

        return {
            packageName: moduleName.substring(0, slashIndex),
            subpathPart: moduleName.substring(slashIndex + 1),
        };
    }

    /**
     * Create a node_modules resolver.
     */
    export function createNodeModulesResolver(options: NodeModulesResolverOptions): NodeModulesResolver {
        return new NodeModulesResolver(options);
    }
}
