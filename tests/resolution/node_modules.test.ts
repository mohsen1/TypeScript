/**
 * Tests for NodeModulesResolver.
 */

namespace ts {
    // Mock file system helper
    function createMockNodeModulesHost(
        files: Map<string, string>,
        directories: Set<string>
    ): ModuleResolutionHost {
        return {
            fileExists: (path) => files.has(normalizePath(path)),
            readFile: (path) => files.get(normalizePath(path)),
            directoryExists: (path) => directories.has(normalizePath(path)),
            getDirectories: () => [],
        };
    }

    describe("NodeModulesResolver", () => {
        describe("basic package resolution", () => {
            it("should resolve package with types field", () => {
                const files = new Map([
                    ["/project/node_modules/lodash/package.json", JSON.stringify({
                        name: "lodash",
                        version: "4.17.21",
                        types: "index.d.ts",
                    })],
                    ["/project/node_modules/lodash/index.d.ts", "declare const _: any;"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/lodash",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("lodash", "/project/src");

                assert.isDefined(result.resolvedPath);
                assert.equal(result.resolvedPath, "/project/node_modules/lodash/index.d.ts");
                assert.isDefined(result.packageInfo);
                assert.equal(result.packageInfo?.name, "lodash");
                assert.equal(result.packageInfo?.version, "4.17.21");
            });

            it("should resolve package with typings field", () => {
                const files = new Map([
                    ["/project/node_modules/react/package.json", JSON.stringify({
                        name: "react",
                        version: "18.0.0",
                        typings: "index.d.ts",
                    })],
                    ["/project/node_modules/react/index.d.ts", "declare namespace React {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/react",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("react", "/project/src");

                assert.isDefined(result.resolvedPath);
                assert.equal(result.resolvedPath, "/project/node_modules/react/index.d.ts");
            });

            it("should fallback to index.d.ts", () => {
                const files = new Map([
                    ["/project/node_modules/simple-pkg/package.json", JSON.stringify({
                        name: "simple-pkg",
                        version: "1.0.0",
                    })],
                    ["/project/node_modules/simple-pkg/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/simple-pkg",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("simple-pkg", "/project/src");

                assert.isDefined(result.resolvedPath);
                assert.equal(result.resolvedPath, "/project/node_modules/simple-pkg/index.d.ts");
            });
        });

        describe("scoped packages", () => {
            it("should resolve scoped packages", () => {
                const files = new Map([
                    ["/project/node_modules/@types/node/package.json", JSON.stringify({
                        name: "@types/node",
                        version: "18.0.0",
                        types: "index.d.ts",
                    })],
                    ["/project/node_modules/@types/node/index.d.ts", "declare namespace NodeJS {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/@types",
                    "/project/node_modules/@types/node",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("@types/node", "/project/src");

                assert.isDefined(result.resolvedPath);
                assert.equal(result.resolvedPath, "/project/node_modules/@types/node/index.d.ts");
                assert.isTrue(result.isTypesPackage);
            });

            it("should resolve scoped package subpaths", () => {
                const files = new Map([
                    ["/project/node_modules/@babel/core/package.json", JSON.stringify({
                        name: "@babel/core",
                        version: "7.0.0",
                    })],
                    ["/project/node_modules/@babel/core/lib/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/@babel",
                    "/project/node_modules/@babel/core",
                    "/project/node_modules/@babel/core/lib",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("@babel/core/lib", "/project/src");

                assert.isDefined(result.resolvedPath);
            });
        });

        describe("@types fallback", () => {
            it("should fallback to @types package", () => {
                const files = new Map([
                    ["/project/node_modules/express/package.json", JSON.stringify({
                        name: "express",
                        version: "4.18.0",
                        main: "index.js",
                    })],
                    ["/project/node_modules/express/index.js", "module.exports = {};"],
                    ["/project/node_modules/@types/express/package.json", JSON.stringify({
                        name: "@types/express",
                        version: "4.17.0",
                        types: "index.d.ts",
                    })],
                    ["/project/node_modules/@types/express/index.d.ts", "declare namespace Express {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/express",
                    "/project/node_modules/@types",
                    "/project/node_modules/@types/express",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                    resolveTypes: true,
                });

                // First try express directly (no .d.ts)
                const expressResult = resolver.resolve("express", "/project/src");

                // If express doesn't have types, it should try @types/express
                // This depends on implementation behavior
                assert.isDefined(expressResult);
            });
        });

        describe("package exports", () => {
            it("should resolve package exports (string)", () => {
                const files = new Map([
                    ["/project/node_modules/pkg-exports/package.json", JSON.stringify({
                        name: "pkg-exports",
                        version: "1.0.0",
                        exports: "./dist/index.js",
                    })],
                    ["/project/node_modules/pkg-exports/dist/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/pkg-exports",
                    "/project/node_modules/pkg-exports/dist",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("pkg-exports", "/project/src");

                // Should resolve to .d.ts sibling of the export
                assert.isDefined(result);
            });

            it("should resolve conditional exports with types condition", () => {
                const files = new Map([
                    ["/project/node_modules/typed-pkg/package.json", JSON.stringify({
                        name: "typed-pkg",
                        version: "1.0.0",
                        exports: {
                            ".": {
                                types: "./types/index.d.ts",
                                import: "./esm/index.js",
                                require: "./cjs/index.js",
                            },
                        },
                    })],
                    ["/project/node_modules/typed-pkg/types/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/typed-pkg",
                    "/project/node_modules/typed-pkg/types",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("typed-pkg", "/project/src");

                assert.isDefined(result.resolvedPath);
                assert.equal(result.resolvedPath, "/project/node_modules/typed-pkg/types/index.d.ts");
            });
        });

        describe("typesVersions", () => {
            it("should resolve using typesVersions", () => {
                const files = new Map([
                    ["/project/node_modules/versioned-types/package.json", JSON.stringify({
                        name: "versioned-types",
                        version: "1.0.0",
                        types: "index.d.ts",
                        typesVersions: {
                            ">=4.0": {
                                "*": ["ts4/*"],
                            },
                            "*": {
                                "*": ["ts3/*"],
                            },
                        },
                    })],
                    ["/project/node_modules/versioned-types/ts4/index.d.ts", "export {}"],
                    ["/project/node_modules/versioned-types/ts3/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/versioned-types",
                    "/project/node_modules/versioned-types/ts4",
                    "/project/node_modules/versioned-types/ts3",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("versioned-types", "/project/src");

                // Should use ts4 path for TypeScript >= 4.0
                assert.isDefined(result.resolvedPath);
            });
        });

        describe("subpath resolution", () => {
            it("should resolve package subpaths", () => {
                const files = new Map([
                    ["/project/node_modules/utils/package.json", JSON.stringify({
                        name: "utils",
                        version: "1.0.0",
                    })],
                    ["/project/node_modules/utils/lib/helpers.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/utils",
                    "/project/node_modules/utils/lib",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const result = resolver.resolve("utils", "/project/src", "lib/helpers");

                assert.isDefined(result.resolvedPath);
                assert.equal(result.resolvedPath, "/project/node_modules/utils/lib/helpers.d.ts");
            });
        });

        describe("package info", () => {
            it("should return package info for resolved module", () => {
                const files = new Map([
                    ["/project/node_modules/lodash/package.json", JSON.stringify({
                        name: "lodash",
                        version: "4.17.21",
                        types: "index.d.ts",
                    })],
                    ["/project/node_modules/lodash/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/lodash",
                ]);
                const host = createMockNodeModulesHost(files, directories);

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                const packageInfo = resolver.getPackageInfo("/project/node_modules/lodash/index.d.ts");

                assert.isDefined(packageInfo);
                assert.equal(packageInfo?.name, "lodash");
                assert.equal(packageInfo?.version, "4.17.21");
                assert.equal(packageInfo?.packageDirectory, "/project/node_modules/lodash");
            });
        });

        describe("caching", () => {
            it("should cache package.json reads", () => {
                let readCount = 0;
                const files = new Map([
                    ["/project/node_modules/cached-pkg/package.json", JSON.stringify({
                        name: "cached-pkg",
                        version: "1.0.0",
                        types: "index.d.ts",
                    })],
                    ["/project/node_modules/cached-pkg/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/cached-pkg",
                ]);

                const host: ModuleResolutionHost = {
                    fileExists: (path) => files.has(normalizePath(path)),
                    readFile: (path) => {
                        readCount++;
                        return files.get(normalizePath(path));
                    },
                    directoryExists: (path) => directories.has(normalizePath(path)),
                };

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                resolver.resolve("cached-pkg", "/project/src");
                const firstReadCount = readCount;

                resolver.resolve("cached-pkg", "/project/src");

                // Second resolution should not read package.json again
                assert.equal(readCount, firstReadCount);
            });

            it("should clear cache", () => {
                let readCount = 0;
                const files = new Map([
                    ["/project/node_modules/cached-pkg/package.json", JSON.stringify({
                        name: "cached-pkg",
                        version: "1.0.0",
                        types: "index.d.ts",
                    })],
                    ["/project/node_modules/cached-pkg/index.d.ts", "export {}"],
                ]);
                const directories = new Set([
                    "/project",
                    "/project/node_modules",
                    "/project/node_modules/cached-pkg",
                ]);

                const host: ModuleResolutionHost = {
                    fileExists: (path) => files.has(normalizePath(path)),
                    readFile: (path) => {
                        readCount++;
                        return files.get(normalizePath(path));
                    },
                    directoryExists: (path) => directories.has(normalizePath(path)),
                };

                const resolver = createNodeModulesResolver({
                    compilerOptions: { target: ScriptTarget.ES2020 },
                    host,
                });

                resolver.resolve("cached-pkg", "/project/src");
                const firstReadCount = readCount;

                resolver.clearCache();

                resolver.resolve("cached-pkg", "/project/src");

                // After cache clear, should read again
                assert.isTrue(readCount > firstReadCount);
            });
        });
    });
}
